// The star catalogue.
//
// Real stars, real coordinates: right ascension in hours, declination in
// degrees, visual magnitude, B-V colour index. Procedural noise can make a
// convincing *quantity* of stars but it cannot make Orion, and a night sky
// you cannot navigate by is just static. So the bright half of the sky is a
// catalogue and the faint remainder is noise - see `stars.js` for the join.
//
// Positions are J2000 to about a tenth of a degree, which is far inside the
// angular size a star is drawn at. Magnitudes drive both size and brightness;
// B-V drives colour, which is why Betelgeuse and Antares are orange and Rigel
// and Spica are blue-white.

